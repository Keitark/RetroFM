#include "retrofm_diagnostic.h"

#include <stdint.h>

typedef struct register_value {
    uint8_t reg;
    uint8_t data;
} register_value;

static const register_value setup[] = {
    {0x20, 0x87}, {0x21, 0x47}, /* algorithm 7, left/right */
    {0x28, 0x4A}, {0x29, 0x4A}, {0x30, 0x00}, {0x31, 0x00},

    {0x40, 0x01}, {0x48, 0x01}, {0x50, 0x01}, {0x58, 0x01},
    {0x41, 0x01}, {0x49, 0x01}, {0x51, 0x01}, {0x59, 0x01},
    {0x60, 0x58}, {0x68, 0x58}, {0x70, 0x58}, {0x78, 0x58},
    {0x61, 0x58}, {0x69, 0x58}, {0x71, 0x58}, {0x79, 0x58},
    {0x80, 0x1F}, {0x88, 0x1F}, {0x90, 0x1F}, {0x98, 0x1F},
    {0x81, 0x1F}, {0x89, 0x1F}, {0x91, 0x1F}, {0x99, 0x1F},
    {0xA0, 0x00}, {0xA8, 0x00}, {0xB0, 0x00}, {0xB8, 0x00},
    {0xA1, 0x00}, {0xA9, 0x00}, {0xB1, 0x00}, {0xB9, 0x00},
    {0xC0, 0x00}, {0xC8, 0x00}, {0xD0, 0x00}, {0xD8, 0x00},
    {0xC1, 0x00}, {0xC9, 0x00}, {0xD1, 0x00}, {0xD9, 0x00},
    {0xE0, 0x0F}, {0xE8, 0x0F}, {0xF0, 0x0F}, {0xF8, 0x0F},
    {0xE1, 0x0F}, {0xE9, 0x0F}, {0xF1, 0x0F}, {0xF9, 0x0F},
    {0x08, 0x78}, {0x08, 0x79}
};

size_t retrofm_diagnostic_event_count(void) {
    return sizeof(setup) / sizeof(setup[0]) + 4U;
}

bool retrofm_diagnostic_event(size_t index, retrofm_event *event) {
    size_t setup_count = sizeof(setup) / sizeof(setup[0]);
    if (event == NULL || index >= retrofm_diagnostic_event_count()) {
        return false;
    }
    event->delta_cycles = 0U;
    event->opcode = RETROFM_OP_YM2151;
    event->reg = 0U;
    event->data = 0U;
    event->flags = 0U;
    if (index < setup_count) {
        event->reg = setup[index].reg;
        event->data = setup[index].data;
    } else if (index == setup_count) {
        event->delta_cycles = UINT32_C(50000000);
        event->reg = 0x08U;
        event->data = 0x00U;
    } else if (index == setup_count + 1U) {
        event->reg = 0x08U;
        event->data = 0x01U;
    } else if (index == setup_count + 2U) {
        event->delta_cycles = UINT32_C(5000000);
        event->opcode = RETROFM_OP_DELAY;
    } else {
        event->opcode = RETROFM_OP_END;
    }
    return true;
}
